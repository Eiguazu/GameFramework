using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace GameFramework.Content.Engine
{
    public class Engine
    {
        // Keeps track of which scene is currently active, one active scene at a time. 
        public Scene CurrentScene { get; private set; }

        // Constructor of inital scene.
        public Engine(Scene startingScene)
        {
            this.CurrentScene = startingScene;
        }

        // Allows you to switch scenes. 
        public void ChangeScene(Scene newScene)
        {
            this.CurrentScene = newScene;
        }

        // If the current scene exits, it its updated. Update is passed down the hierarchy. 
        public void Update(GameTime gameTime)
        {
            CurrentScene?.Update(gameTime);
        }

        // If the current scene exits, it is drawn. Draw is passed down the hierarchy. 
        public void Draw(SpriteBatch spriteBatch)
        {
            CurrentScene?.Draw(spriteBatch); 
        }
    }
}








