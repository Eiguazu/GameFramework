using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;
using System.Collections.Generic;

namespace GameFramework.Content.Engine
{
    public class Engine
    {
        // Keeps track of which scene is currently active, one active scene at a time. 
        public Scene CurrentScene { get; private set; }

        // Constructor of inital scene.
        public Engine(Scene startingScene)
        {
            this.CurrentScene = startingScene;
        }

        // Changes the scene to a new scene. Counts out the persistant objects, so they stay. 
        public void ChangeScene(Scene newScene)
        {
            if (CurrentScene != null)
            {
                List<GameObject> persistentObjects = CurrentScene.GetPersistentObjects();
                for (int i = 0; i < persistentObjects.Count; i++)
                {
                    GameObject obj = persistentObjects[i];
                    CurrentScene.Remove(obj);
                    newScene.Add(obj); 
                }
            }

            CurrentScene = newScene; 

        }

        // If the current scene exits, it its updated. Update is passed down the hierarchy. ? for null.
        public void Update(GameTime gameTime)
        {
            CurrentScene?.Update(gameTime);
        }

        // If the current scene exits, it is drawn. Draw is passed down the hierarchy. ? for null. 
        public void Draw(SpriteBatch spriteBatch, bool drawUI)
        {
            CurrentScene?.Draw(spriteBatch, drawUI);
        }
    }
}








